#!/usr/bin/env bash
# Sets up this workspace: dependencies, .env, the shared database and mail containers,
# this workspace's two databases, migrations, seed data and the test browser.
# Safe to run more than once.
set -euo pipefail

source "$(dirname "${BASH_SOURCE[0]}")/lib/workspace-env.sh"
cd "$REPO_ROOT"

PNPM_VERSION="12.21.0"

if ! command -v pnpm >/dev/null 2>&1; then
  echo "pnpm not found; installing pnpm@$PNPM_VERSION"
  npm install --global "pnpm@$PNPM_VERSION"
fi

pnpm install --frozen-lockfile

# Keep the secret of an existing .env, so sessions survive a second run.
AUTH_SECRET="$(sed -n 's/^AUTH_SECRET=//p' .env 2>/dev/null | head -n 1 || true)"
if [ -z "$AUTH_SECRET" ]; then
  AUTH_SECRET="$(openssl rand -hex 32)"
fi

DB_URL_BASE="postgres://padvinder:padvinder@localhost:54329"
cat >.env <<ENV
# Generated by scripts/setup-workspace.sh. Put overrides in .env.local.
WORKSPACE=$WORKSPACE
DATABASE_URL=$DB_URL_BASE/padvinder_$WORKSPACE
TEST_DATABASE_URL=$DB_URL_BASE/padvinder_${WORKSPACE}_test
API_PORT=$API_PORT
MOBILE_PORT=$MOBILE_PORT
PORTAL_PORT=$PORTAL_PORT
STORYBOOK_PORT=$STORYBOOK_PORT
ALLOWED_ORIGINS=http://localhost:$MOBILE_PORT,http://localhost:$PORTAL_PORT
AUTH_SECRET=$AUTH_SECRET
PUBLIC_ORIGIN=http://localhost:$MOBILE_PORT
SMTP_HOST=localhost
SMTP_PORT=54325
MAIL_FROM=PadVinder <noreply@padvinder.test>
LOGIN_RATE_LIMITS=off
MAILPIT_URL=http://localhost:54326
ENV

docker compose up -d --wait db mail

# On a fresh volume the health check can pass against the temporary server of
# the first start. That server has no TCP listener, so wait for one that has.
for _ in $(seq 1 30); do
  docker compose exec -T db psql -h localhost -U padvinder -d padvinder -Atc "select 1" >/dev/null 2>&1 && break
  sleep 1
done

for database in "padvinder_$WORKSPACE" "padvinder_${WORKSPACE}_test"; do
  exists="$(docker compose exec -T db psql -U padvinder -d padvinder -Atc \
    "select 1 from pg_database where datname = '$database'")"
  if [ -z "$exists" ]; then
    docker compose exec -T db psql -U padvinder -d padvinder -c "create database \"$database\""
  fi
done

pnpm db:migrate
pnpm db:seed
pnpm exec playwright install chromium

echo "Workspace '$WORKSPACE' is ready (API on port $API_PORT)."
